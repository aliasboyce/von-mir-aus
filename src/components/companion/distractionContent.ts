export interface DistractionItem {
  kind: DistractionKind;
  text: string;
  textEn: string;
  /** revealed on tap for kinds with no structured options (fakt-adjacent
   * frage without choices) — for raetsel/frage/wortspiel items that DO
   * have `options`, this is shown only as the final explanation after
   * the person has answered (see DistractionQuiz.tsx), not tapped
   * directly. */
  answer?: string;
  answerEn?: string;
  /** A short "why" shown alongside the answer once revealed — the
   * difference between "here's the answer" and "here's the answer, and
   * here's the reasoning that gets you there", which the brief
   * specifically asked for on top of the bare answer. */
  explanation?: string;
  explanationEn?: string;
  /** 2-5 choices for kinds with a checkable answer; when present, the
   * UI shows real multiple-choice with correct/incorrect feedback and
   * one retry instead of a flat tap-to-reveal. correctIndex indexes
   * into options/optionsEn. Absent entirely for open-ended items
   * (observations, "what if" questions) that have no single answer. */
  options?: string[];
  optionsEn?: string[];
  correctIndex?: number;
  difficulty?: DistractionDifficulty;
  /** Point 3 — for schwer/sehr_schwer items rendered with free-text
   * input instead of multiple choice: a partial nudge shown on request,
   * before the person commits to seeing the full answer. Optional —
   * items without one simply skip straight to "Lösung anzeigen". */
  hint?: string;
  hintEn?: string;
  /** facts only — a real, named source, never invented. Facts that
   * couldn't be traced to a reliable source were left out entirely
   * rather than used without one. */
  source?: string;
  sourceUrl?: string;
}

